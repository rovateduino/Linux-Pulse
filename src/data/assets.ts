export const ASSETS: readonly AssetDef[] = IQ_OPTION_ASSETS
export const DEFAULT_SYMBOL = 'EURUSD'
export const LAB_DEFAULT_SYMBOL = BINANCE_ASSETS[0].symbol
export const SIMULATED_SYMBOL = 'SIMULADO'
export const LAB_SYMBOLS: readonly string[] = [
  ...BINANCE_ASSETS.map((asset) => asset.symbol),
  SIMULATED_SYMBOL,
]

export const LAB_TIMEFRAME_LABEL: Record<LabTimeframe, string> = {
  '1m': 'M1',
  '5m': 'M5',
  '15m': 'M15',
}

export const LAB_CONFIRMATION_LABEL: Record<LabConfirmation, string> = {
  '15m': 'M15',
  '30m': 'M30',
}

export function labName(symbol: string): string {
  if (symbol === SIMULATED_SYMBOL) return 'Simulado'
  return BINANCE_ASSETS.find((asset) => asset.symbol === symbol)?.name ?? symbol
}

export function labDecimals(symbol: string): number {
  if (symbol === SIMULATED_SYMBOL) return 2
  return BINANCE_ASSETS.find((asset) => asset.symbol === symbol)?.decimals ?? 2
}

export function labSource(symbol: string): LabSource {
  return symbol === SIMULATED_SYMBOL ? 'simulado' : 'binance'
}

export const TIMEFRAME_SECONDS: Record<Timeframe, number> = {
  '1m': 60,
  '5m': 300,
  '15m': 900,
}

export const TIMEFRAME_LABEL: Record<Timeframe, string> = {
  '1m': 'M1',
  '5m': 'M5',
  '15m': 'M15',
}

export function findAsset(symbol: string): AssetDef {
  if (symbol === SIMULATED_SYMBOL) return BINANCE_ASSETS[0]
  return ASSETS.find((asset) => asset.symbol === symbol) ?? BINANCE_ASSETS[0]
}
